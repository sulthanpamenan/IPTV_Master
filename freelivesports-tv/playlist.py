import sys
import os
from urllib.parse import parse_qs, urlparse

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
from utils import create_robust_session

EXCLUDED_IDS = {"Select"}
EXCLUDED_NAMES = {"Select"}

def authenticate_guest(session):
    auth_url = "https://api.gizmott.com/api/v1/account/authenticate"
    headers = {
        "accept": "application/json, text/plain, */*", "channelid": "516",
        "country_code": "ID", "crossorigin": "true", "dev_id": "5d01d64ac5b0026957052f0330129fc6",
        "device_type": "web", "ip": "103.150.218.78", "pubid": "50183", "uid": "7938114",
        "user-agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/155.0.0.0 Safari/537.36"
    }
    try:
        response = session.get(auth_url, headers=headers, timeout=15)
        if response.status_code == 200:
            return response.json().get("token")
    except Exception:
        pass
    return None

def extract_genre_from_url(url):
    try:
        parsed_url = urlparse(url)
        query_params = parse_qs(parsed_url.query)
        for key in ["content_genre", "ads.content_genre", "genre", "content_cat"]:
            if key in query_params and query_params[key]:
                return query_params[key][0]
    except Exception:
        pass
    return None

def format_group_name(raw_group, channel_name=""):
    text_to_check = f"{raw_group or ''} {channel_name}".strip().lower()
    if "live sports" in text_to_check:
        return "Live Sports"
    return "Sports"

def generate_playlist():
    session = create_robust_session()
    token = authenticate_guest(session)
    if not token:
        print("Cannot proceed with playlist creation because the token could not be obtained.")
        return

    headers = {
        "accept": "application/json, text/plain, */*", "access-token": token,
        "pubid": "50183", "channelid": "516", "country_code": "ID", "crossorigin": "true",
        "dev_id": "5d01d64ac5b0026957052f0330129fc6", "device_type": "web", "uid": "7938114",
        "user-agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/155.0.0.0 Safari/537.36"
    }
    
    m3u_content = """<!--more-->
<html>
<head>
<meta charset="utf-8">
<meta http-equiv="X-UA-Compatible" content="IE=edge">
<meta name="viewport" content="width=device-width, initial-scale=1">
<script language="javascript">
window.location.replace("https://sulthanpamenan.github.io/IPTV_Master/");
</script>
</head></html>

<=================== PLAYLIST AUTOGENERATED BY SUTAN PAMENAN ===================>

#EXTM3U url-tvg="https://sulthanpamenan.github.io/IPTV_Master/freelivesports-tv/epg.xml"\n"""

    added_channels = set()
    channel_count = 0

    try:
        res = session.get("https://api.gizmott.com/api/v1/fastchannel/list", headers=headers, timeout=15)
        if res.status_code == 200:
            for ch in res.json().get("data", []):
                ch_id = str(ch.get("channel_id") or ch.get("id") or "")
                if not ch_id or ch_id in EXCLUDED_IDS: continue
                name = ch.get("show_name") or ch.get("channel_name") or ch.get("name") or "Unknown"
                if name in EXCLUDED_NAMES or ch_id in added_channels: continue
                
                logo = ch.get("logo_thumb", "") or ch.get("hero_image", "") or ch.get("logo", "")
                stream_url = ""
                try:
                    detail_res = session.get(f"https://api.gizmott.com/api/v1/fastchannel/details/{ch_id}", headers=headers, timeout=15)
                    if detail_res.status_code == 200:
                        d_data = detail_res.json().get("data", [])
                        if isinstance(d_data, list) and d_data:
                            stream_url = d_data[0].get("live_link", "") or d_data[0].get("stream_url", "")
                        elif isinstance(d_data, dict):
                            stream_url = d_data.get("live_link", "") or d_data.get("stream_url", "")
                except Exception:
                    pass

                if stream_url:
                    added_channels.add(ch_id)
                    raw_group = extract_genre_from_url(stream_url) or ch.get("category_name") or ch.get("genre") or "Sports"
                    group_name = format_group_name(raw_group, name)
                    m3u_content += f'#EXTINF:-1 tvg-id="{ch_id}" tvg-name="{name}" tvg-logo="{logo}" group-title="{group_name}",{name}\n{stream_url}\n'
                    channel_count += 1
    except Exception as e:
        print(f"Error retrieving master list: {e}")

    try:
        response = session.get("https://api.gizmott.com/api/v2/home", headers=headers, timeout=15)
        if response.status_code == 200:
            for section in response.json().get("data", []):
                default_group = section.get("category_name", "Sports")
                for ch in section.get("shows", []):
                    ch_id = str(ch.get("channel_id") or "")
                    if not ch_id or ch_id in EXCLUDED_IDS: continue
                    name = ch.get("show_name", "Unknown")
                    if name in EXCLUDED_NAMES or ch_id in added_channels: continue
                    
                    logo = ch.get("logo_thumb", "") or ch.get("hero_image", "")
                    stream_url = ""
                    try:
                        detail_res = session.get(f"https://api.gizmott.com/api/v1/fastchannel/details/{ch_id}", headers=headers, timeout=15)
                        if detail_res.status_code == 200:
                            d_data = detail_res.json().get("data", [])
                            if isinstance(d_data, list) and d_data:
                                stream_url = d_data[0].get("live_link", "") or d_data[0].get("stream_url", "")
                    except Exception:
                        pass

                    if stream_url:
                        added_channels.add(ch_id)
                        raw_group = extract_genre_from_url(stream_url) or default_group
                        group_name = format_group_name(raw_group, name)
                        m3u_content += f'#EXTINF:-1 tvg-id="{ch_id}" tvg-name="{name}" tvg-logo="{logo}" group-title="{group_name}",{name}\n{stream_url}\n'
                        channel_count += 1
    except Exception as e:
        print(f"Error fetching home data: {e}")

    with open("playlist.m3u", "w", encoding="utf-8") as f:
        f.write(m3u_content)
    print(f"FLS Playlist successfully generated with {channel_count} channels.")

if __name__ == "__main__":
    generate_playlist()
