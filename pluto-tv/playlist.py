import sys
import os
import uuid
import requests

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
from utils import create_robust_session

HEADERS = {
    'User-Agent': 'Mozilla/5.0 (Linux; Android 14; Chromecast HD Build/UTTC.250917.004; wv) AppleWebKit/537.36 (KHTML, like Gecko) Version/4.0 Chrome/146.0.7680.177 Mobile Safari/537.36',
    'Accept': 'application/json',
    'Origin': 'https://pluto.tv',
    'Referer': 'https://pluto.tv/'
}

EPG_URL = "https://sulthanpamenan.github.io/IPTV_Master/pluto-tv/epg.xml"

def get_pluto_session():
    device_id = str(uuid.uuid4())
    session_id = str(uuid.uuid4())
    client_id = str(uuid.uuid4())
    
    boot_url = (
        f"https://boot.pluto.tv/v4/start"
        f"?appName=androidtv&appVersion=9.22.0-ba99318afe50de3c8a02021f4c92fd52f2c47a00"
        f"&clientDeviceType=1&clientID={client_id}&clientModelNumber=1.0.0"
        f"&deviceId={device_id}&deviceMake=googletv&deviceModel=smarttv&deviceType=androidtv"
        f"&deviceVersion=143.0.0&marketingRegion=US&serverSideAds=true&sessionID={session_id}"
    )
    
    token = ""
    channels = []
    session = create_robust_session(HEADERS)
    
    try:
        res = session.get(boot_url, timeout=15)
        if res.status_code == 200:
            data = res.json()
            token = data.get('sessionToken', '')
            channels = data.get('channels', [])
            print(f"[INFO] Android TV Token acquired successfully: {token[:20]}...")
    except Exception as e:
        print(f"[ERROR] Boot fetch error: {e}")

    if not channels:
        try:
            res_v2 = session.get("https://api.pluto.tv/v2/channels", timeout=15)
            if res_v2.status_code == 200:
                channels = res_v2.json()
        except Exception as e:
            print(f"[ERROR] Channels v2 fetch error: {e}")

    return token, device_id, session_id, client_id, channels

def build_m3u():
    try:
        token, device_id, session_id, client_id, channels = get_pluto_session()
        m3u_lines = [
            "<!--more-->", "<html>", "<head>", '<meta charset="utf-8">',
            '<meta http-equiv="X-UA-Compatible" content="IE=edge">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            "<script language=\"javascript\">",
            'window.location.replace("https://sulthanpamenan.github.io/IPTV_Master/pluto-tv/");',
            "</script>", "</head></html>", "",
            "<================== PLAYLIST AUTOGENERATED BY SUTAN PAMENAN ==================>",
            "", f'#EXTM3U url-tvg="{EPG_URL}"'
        ]
            
        for ch in channels:
            ch_id = ch.get('id') or ch.get('_id')
            if not ch_id:
                continue

            name = ch.get('name', 'Pluto Channel')
            logo = ''
            if isinstance(ch.get('colorLogoPNG'), dict):
                logo = ch.get('colorLogoPNG', {}).get('path', '')
            elif isinstance(ch.get('logo'), str):
                logo = ch.get('logo')

            group = ch.get('category', 'Pluto TV')

            stream_link = (
                f"https://cfd-v4-service-channel-stitcher-use1-1.prd.pluto.tv/v2/stitch/hls/channel/{ch_id}/master.m3u8"
                f"?advertisingId=&appName=androidtv&appVersion=9.22.0-ba99318afe50de3c8a02021f4c92fd52f2c47a00"
                f"&app_name=androidtv&clientDeviceType=1&clientID={client_id}&clientModelNumber=1.0.0"
                f"&country=US&deviceDNT=false&deviceId={device_id}&deviceLat=47.3000&deviceLon=-122.3700"
                f"&deviceMake=googletv&deviceModel=smarttv&deviceType=androidtv&deviceVersion=143.0.0"
                f"&marketingRegion=US&serverSideAds=true&sessionID={session_id}&sid={session_id}"
                f"&userId=&jwt={token}&masterJWTPassthrough=true&includeExtendedEvents=true"
            )

            m3u_lines.append(f'#EXTINF:-1 tvg-id="{ch_id}" tvg-name="{name}" tvg-logo="{logo}" group-title="{group}",{name}')
            m3u_lines.append(stream_link)

        with open("playlist.m3u", "w", encoding="utf-8") as f:
            f.write("\n".join(m3u_lines))
            
        print("[SUCCESS] Pluto TV playlist.m3u updated successfully!")
    except Exception as e:
        print(f"[ERROR] Failed to build Pluto TV playlist: {e}")

if __name__ == "__main__":
    build_m3u()
